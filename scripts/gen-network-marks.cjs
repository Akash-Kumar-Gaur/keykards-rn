const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '../assets/networks');
const map = {
  Visa: 'visa.svg',
  Mastercard: 'mastercard.svg',
  Amex: 'amex.svg',
  Diners: 'diners.svg',
  RuPay: 'rupay.svg',
};

function sanitize(xml) {
  return (
    xml
      .trim()
      // Drop XML prolog / doctype / comments / editor desc — SvgXml wants a bare <svg>
      .replace(/<\?xml[\s\S]*?\?>/g, '')
      .replace(/<!DOCTYPE[\s\S]*?>/gi, '')
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/<desc>[\s\S]*?<\/desc>/gi, '')
      // Fabric.js emits invalid transforms on empty groups — neutralize them
      .replace(/transform="matrix\([^"]*(Infinity|NaN)[^"]*\)"/g, 'transform="matrix(1 0 0 1 0 0)"')
      // Guard against negative root dimensions (e.g. height="-133")
      .replace(/\s(height|width)="-[^"]*"/g, '')
      .trim()
  );
}

const out = {};
for (const [k, f] of Object.entries(map)) {
  const file = path.join(dir, f);
  if (!fs.existsSync(file)) {
    console.warn('skip missing', f);
    continue;
  }
  out[k] = sanitize(fs.readFileSync(file, 'utf8'));
}

const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n');

const ts = `/**
 * Network mark SVG XML for NetworkBadge (SvgXml).
 * Regenerated by: node scripts/gen-network-marks.cjs
 * Source files: assets/networks/*.svg
 * NetworkBadge namespaces element ids per instance, so defs/clipPaths are kept.
 */
import type { CardNetwork } from '@/types/card';

export const NETWORK_SVG: Partial<Record<CardNetwork, string>> = {
${body}
};

/** Marks without a full-bleed colored background need a solid backdrop in the clip. */
export const NETWORK_NEEDS_BACKDROP: Partial<Record<CardNetwork, string>> = {
  RuPay: '#FFFFFF',
};

export function hasNetworkSvg(network: CardNetwork): boolean {
  return Boolean(NETWORK_SVG[network]);
}
`;

fs.writeFileSync(
  path.join(__dirname, '../src/components/vault/networkMarks.ts'),
  ts,
);
console.log(
  'wrote',
  Object.keys(out),
  Object.values(out).map((s) => s.length),
);
